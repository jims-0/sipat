"""Measure the trained model on the held-out TEST photos (never used in training).

    python scripts/evaluate.py

Writes app/ml/model/evaluation_report.json (the app reads its confidence
threshold from here) and docs/EVALUATION.md (the human-readable report, with
a confusion matrix image if matplotlib is installed). Every number quoted in
the README must come from this report.
"""

import json
import sys
import time
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import tg_data  # noqa: E402

from app.ml.classes import CLASSES  # noqa: E402

THRESHOLDS = [0.0, 0.5, 0.6, 0.7, 0.8, 0.9]
TARGET_ANSWERED_ACCURACY = 0.97


def main():
    import keras
    import numpy as np

    model = keras.models.load_model(tg_data.MODEL_DIR / "tanim_guard.keras")
    labels = json.loads((tg_data.MODEL_DIR / "labels.json").read_text())
    if labels != tg_data.LABELS:
        raise SystemExit("labels.json does not match app/ml/classes.py - retrain")

    test = tg_data.split_files()["test"]
    y_true = np.array([l for _, l in test])
    started = time.time()
    probs = model.predict(tg_data.load_dataset(test, batch_size=64), verbose=0)
    seconds = time.time() - started
    y_pred = probs.argmax(1)
    conf = probs.max(1)
    n = len(labels)

    cm = np.zeros((n, n), dtype=int)
    for t, p in zip(y_true, y_pred):
        cm[t, p] += 1
    per_class = []
    for i, folder in enumerate(labels):
        tp = cm[i, i]
        prec = tp / cm[:, i].sum() if cm[:, i].sum() else 0.0
        rec = tp / cm[i, :].sum() if cm[i, :].sum() else 0.0
        f1 = 2 * prec * rec / (prec + rec) if prec + rec else 0.0
        per_class.append({"class": folder, "name": CLASSES[folder]["name"],
                          "precision": round(float(prec), 4), "recall": round(float(rec), 4),
                          "f1": round(float(f1), 4), "support": int(cm[i, :].sum())})

    top3 = float(np.mean([t in np.argsort(p)[-3:] for t, p in zip(y_true, probs)]))
    thresholds = []
    for th in THRESHOLDS:
        answered = conf >= th
        acc = float((y_pred[answered] == y_true[answered]).mean()) if answered.any() else 0.0
        thresholds.append({"threshold": th, "answered_share": round(float(answered.mean()), 4),
                           "accuracy_when_answered": round(acc, 4)})
    recommended = next((t["threshold"] for t in thresholds
                        if t["threshold"] > 0 and t["accuracy_when_answered"] >= TARGET_ANSWERED_ACCURACY),
                       0.6)

    confusions = sorted(((int(cm[i, j]), labels[i], labels[j]) for i in range(n) for j in range(n)
                         if i != j and cm[i, j]), reverse=True)[:8]
    report = {
        "test_photos": int(len(test)),
        "accuracy": round(float((y_pred == y_true).mean()), 4),
        "top3_accuracy": round(top3, 4),
        "macro_f1": round(float(np.mean([c["f1"] for c in per_class])), 4),
        "per_class": per_class,
        "thresholds": thresholds,
        "recommended_threshold": recommended,
        "top_confusions": [{"count": c, "true": t, "predicted": p} for c, t, p in confusions],
        "confusion_matrix": cm.tolist(),
        "ms_per_photo_batched_cpu": round(1000 * seconds / len(test), 1),
        "model_size_mb": round((tg_data.MODEL_DIR / "tanim_guard.keras").stat().st_size / 1e6, 1),
        "note": ("Test photos are PlantVillage lab photos (single leaf, plain background). "
                 "Accuracy on phone photos taken in a field is expected to be lower and has "
                 "not been measured yet."),
    }
    (tg_data.MODEL_DIR / "evaluation_report.json").write_text(json.dumps(report, indent=1))
    write_markdown(report, labels, cm)
    print(json.dumps({k: report[k] for k in ("test_photos", "accuracy", "top3_accuracy",
                                              "macro_f1", "recommended_threshold")}, indent=1))


def write_markdown(r, labels, cm):
    docs = tg_data.ROOT / "docs"
    docs.mkdir(exist_ok=True)
    info = json.loads((tg_data.MODEL_DIR / "training_info.json").read_text())
    lines = [
        "# Tanim Guard - model evaluation",
        "",
        "Generated by `scripts/evaluate.py`. Do not edit by hand; re-run the script.",
        "",
        f"- Dataset: {info['dataset']}",
        f"- Model: {info['architecture']}, {info['image_size']}x{info['image_size']} input, "
        f"{r['model_size_mb']} MB",
        f"- Split by file-name hash: {info['train_photos']} train (capped at "
        f"{info['max_train_per_class']}/class), {info['val_photos']} validation, "
        f"**{r['test_photos']} test photos never seen in training**",
        f"- Training: {info['head_epochs']} head epochs + {info['fine_epochs']} fine-tune epochs, "
        f"{info['training_minutes']} min on CPU",
        "",
        "## Results on the test set",
        "",
        f"| Accuracy | Top-3 accuracy | Macro F1 | CPU time / photo (batched) |",
        f"|---|---|---|---|",
        f"| {r['accuracy']:.1%} | {r['top3_accuracy']:.1%} | {r['macro_f1']:.3f} | "
        f"{r['ms_per_photo_batched_cpu']} ms |",
        "",
        f"> {r['note']}",
        "",
        "## Saying \"unsure\" instead of guessing",
        "",
        "Below the confidence threshold the app answers \"not sure - retake the photo\".",
        "",
        "| Threshold | Photos answered | Accuracy on answered |",
        "|---|---|---|",
    ]
    for t in r["thresholds"]:
        lines.append(f"| {t['threshold']:.1f} | {t['answered_share']:.1%} | {t['accuracy_when_answered']:.1%} |")
    lines += ["", f"The app uses **{r['recommended_threshold']}** (lowest threshold reaching "
              f"{TARGET_ANSWERED_ACCURACY:.0%} accuracy on answered photos).", "",
              "## Per class", "", "| Class | Precision | Recall | F1 | Test photos |", "|---|---|---|---|---|"]
    for c in r["per_class"]:
        lines.append(f"| {c['name']} | {c['precision']:.3f} | {c['recall']:.3f} | {c['f1']:.3f} | {c['support']} |")
    lines += ["", "## Most common mistakes", "", "| Count | True | Predicted as |", "|---|---|---|"]
    for c in r["top_confusions"]:
        lines.append(f"| {c['count']} | {CLASSES[c['true']]['name']} | {CLASSES[c['predicted']]['name']} |")
    if _plot(cm, labels, docs / "confusion_matrix.png"):
        lines += ["", "![Confusion matrix](confusion_matrix.png)"]
    (docs / "EVALUATION.md").write_text("\n".join(lines) + "\n", encoding="utf-8")


def _plot(cm, labels, path) -> bool:
    try:
        import matplotlib
        matplotlib.use("Agg")
        import matplotlib.pyplot as plt
    except ImportError:
        return False
    names = [CLASSES[l]["name"] for l in labels]
    fig, ax = plt.subplots(figsize=(11, 10))
    ax.imshow(cm, cmap="Greens")
    ax.set_xticks(range(len(names)), names, rotation=90, fontsize=7)
    ax.set_yticks(range(len(names)), names, fontsize=7)
    ax.set_xlabel("Predicted")
    ax.set_ylabel("True")
    for i in range(len(names)):
        for j in range(len(names)):
            if cm[i, j]:
                ax.text(j, i, cm[i, j], ha="center", va="center", fontsize=6,
                        color="white" if cm[i, j] > cm.max() / 2 else "black")
    fig.tight_layout()
    fig.savefig(path, dpi=130)
    return True


if __name__ == "__main__":
    main()
